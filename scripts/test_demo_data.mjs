import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { validateDemoData } from "../src/demo/data.ts";
const fixture = JSON.parse(await fs.readFile(new URL("../public/assets/demo/demo-data.json", import.meta.url), "utf8"));
assert.equal(validateDemoData(fixture), fixture);
assert.equal(fixture.regions.filter(r => r.level === "省").length, 31);
assert.equal(fixture.chains.length, 10);
assert.equal(fixture.cities.length, 50);
assert.equal(new Set(fixture.cities.map(c => c.id)).size, 50);
assert.deepEqual(fixture.profile.indicators.map(r => r.year), [2021, 2022, 2023, 2024, 2025]);
assert.ok(fixture.companies.find(c => c.id === "capchem").logo === null || typeof fixture.companies.find(c => c.id === "capchem").logo === "string");
const reject = (change, expected) => { const data = structuredClone(fixture); change(data); assert.throws(() => validateDemoData(data), expected); };
reject(d => { d.regions[0].gdp = "not a number"; }, /gdp/);
reject(d => { d.regions[0].shares = [10, 90]; }, /shares/);
reject(d => { d.companies[0].logo = "javascript:alert(1)"; }, /logo/);
reject(d => { d.companies[0].name = ""; }, /name/);
reject(d => { d.profile.chainLinks[0].stageId = "does-not-exist"; }, /找不到引用/);
reject(d => { d.cities[0].coordinate = [200, 91]; }, /coordinate/);
reject(d => { d.cities[0].scores[0] = 101; }, /scores/);
reject(d => { d.regions.push(structuredClone(d.regions[0])); }, /ID 重复/);
reject(d => { d.profile.indicators[0].gdp = NaN; }, /gdp/);
const zero = structuredClone(fixture); zero.regions[0].gdp = 0; zero.profile.indicators[0].gdp = 0;
assert.equal(validateDemoData(zero).regions[0].gdp, 0);
console.log("Demo dataset: fixture coverage and 10 structural rejection/zero cases passed.");
